# 函数职责：完成 export_memory_markdown 对应的业务处理。
# 参数关系：output_dir 表示output_dir 对应的文件系统位置。
# 返回关系：结果返回给调用层，并由调用层继续持久化、发送事件或推进运行状态。
def export_memory_markdown(*, output_dir: Path | None = None) -> list[Path]:
    """Regenerate human-readable memory views from the canonical SQLite rows."""

    # 变量说明：target 表示当前步骤使用的 target 值。
    target = (output_dir or memory_projection_directory()).resolve()
    # 变量说明：written 表示当前步骤使用的 written 值。
    written: list[Path] = []
    with _projection_lock:
        with _projection_file_lock(target):
            # Acquire the cross-process file lock before reading. Regardless of
            # exporter arrival order, every later lock holder sees all memory
            # commits that completed while it waited and cannot restore an old
            # snapshot over a newer one.
            with database_module.SessionLocal() as db:
                # 变量说明：rows 表示当前流程使用的 rows 集合。
                rows = list(db.scalars(select(Memory).order_by(
                    Memory.created_at.asc(), Memory.id.asc()
                )))
                # 变量说明：workspace_names 表示当前流程使用的 workspace_names 集合。
                workspace_names = {
                    item.id: item.name for item in db.scalars(select(Workspace))
                }
                # 变量说明：session_titles 表示当前流程使用的 session_titles 集合。
                session_titles = {
                    item.id: item.title for item in db.scalars(select(ChatSession))
                }
                # 变量说明：rollouts 表示当前流程使用的 rollouts 集合。
                rollouts = list(db.scalars(select(MemoryRollout).order_by(
                    MemoryRollout.created_at.asc(), MemoryRollout.id.asc()
                )))
                # 变量说明：memory_skills 表示当前流程使用的 memory_skills 集合。
                memory_skills = list(db.scalars(select(MemorySkill).where(
                    MemorySkill.status == "active"
                ).order_by(MemorySkill.name.asc(), MemorySkill.id.asc())))
            # 变量说明：active 表示当前步骤使用的 active 值。
            active = [item for item in rows if item.status == "active"]
            # 变量说明：active_catalog 表示当前步骤使用的 active_catalog 值。
            active_catalog = sorted(
                active,
                key=lambda item: (item.scope, str(item.scope_id or ""), item.name.casefold(), item.id),
            )
            # 变量说明：documents 表示当前流程使用的 documents 集合。
            documents = {
                target / "memory_summary.md": _render_summary(
                    active, workspace_names, session_titles, memory_skills
                ),
                target / "MEMORY.md": _render_catalog(active_catalog, workspace_names, session_titles),
                target / "raw_memories.md": _render_raw_memories(
                    rows, workspace_names, session_titles, rollouts
                ),
            }
            for path, content in documents.items():
                _atomic_write_text(path, content)
                written.append(path)

            # 变量说明：session_directory 表示当前步骤使用的 session_directory 值。
            session_directory = target / "session_summaries"
            # 变量说明：grouped 表示当前步骤使用的 grouped 值。
            grouped: dict[str, list[Memory]] = defaultdict(list)
            for memory in active:
                if memory.source_session_id:
                    grouped[memory.source_session_id].append(memory)
            # 变量说明：expected 表示当前步骤使用的 expected 值。
            expected: set[Path] = set()
            for session_id, memories in sorted(grouped.items()):
                # 变量说明：path 表示当前文件或目录路径。
                path = session_directory / f"{session_id}.md"
                # 变量说明：content 表示待处理或返回的正文内容。
                content = _render_session_memories(
                    session_id,
                    session_titles.get(session_id, session_id),
                    sorted(memories, key=lambda item: (item.name.casefold(), item.id)),
                    workspace_names,
                    session_titles,
                )
                _atomic_write_text(path, content)
                expected.add(path)
                written.append(path)
            if session_directory.is_dir():
                for path in session_directory.glob("*.md"):
                    if path in expected:
                        continue
                    try:
                        # 变量说明：first_line 表示当前步骤使用的 first_line 值。
                        first_line = path.open("r", encoding="utf-8", errors="replace").readline().strip()
                    except OSError:
                        continue
                    if first_line == GENERATED_MEMORY_MARKER:
                        path.unlink()

            # 变量说明：rollout_directory 表示当前步骤使用的 rollout_directory 值。
            rollout_directory = target / "rollout_summaries"
            # 变量说明：expected_rollouts 表示当前流程使用的 expected_rollouts 集合。
            expected_rollouts: set[Path] = set()
            for rollout in rollouts:
                # 变量说明：path 表示当前文件或目录路径。
                path = rollout_directory / f"{rollout.id}.md"
                _atomic_write_text(
                    path,
                    _render_rollout_summary(
                        rollout,
                        session_titles.get(rollout.source_session_id, rollout.source_session_id),
                    ),
                )
                expected_rollouts.add(path)
                written.append(path)
            if rollout_directory.is_dir():
                for path in rollout_directory.glob("*.md"):
                    if path in expected_rollouts:
                        continue
                    try:
                        # 变量说明：first_line 表示当前步骤使用的 first_line 值。
                        first_line = path.open("r", encoding="utf-8", errors="replace").readline().strip()
                    except OSError:
                        continue
                    if first_line == GENERATED_MEMORY_MARKER:
                        path.unlink()

            # 变量说明：skill_directory 表示当前步骤使用的 skill_directory 值。
            skill_directory = target / "skills"
            # 变量说明：expected_skills 表示当前流程使用的 expected_skills 集合。
            expected_skills: set[Path] = set()
            for skill in memory_skills:
                # 变量说明：safe_name 表示当前步骤使用的 safe_name 值。
                safe_name = re.sub(r"[^a-zA-Z0-9_.-]+", "-", skill.name.strip()).strip("-.") or skill.id
                # 变量说明：path 表示当前文件或目录路径。
                path = skill_directory / safe_name / "SKILL.md"
                # 变量说明：content 表示待处理或返回的正文内容。
                content = "\n".join([
                    GENERATED_MEMORY_MARKER,
                    "---",
                    f"name: {skill.name}",
                    f"description: {skill.description}",
                    "---",
                    "",
                    skill.content,
                    "",
                    "## Memory provenance",
                    "",
                    *[f"- rollout:{rollout_id}" for rollout_id in skill.source_rollout_ids or []],
                    "",
                ])
                _atomic_write_text(path, content)
                expected_skills.add(path)
                written.append(path)
            if skill_directory.is_dir():
                for path in skill_directory.glob("*/SKILL.md"):
                    if path in expected_skills:
                        continue
                    try:
                        # 变量说明：first_line 表示当前步骤使用的 first_line 值。
                        first_line = path.open("r", encoding="utf-8", errors="replace").readline().strip()
                    except OSError:
                        continue
                    if first_line == GENERATED_MEMORY_MARKER:
                        path.unlink()
                        try:
                            path.parent.rmdir()
                        except OSError:
                            pass
    return written


