# 函数职责：完成 scope_label 对应的业务处理。
# 参数关系：memory 表示当前步骤使用的 memory 值；workspace_names 表示当前流程使用的 workspace_names 集合；session_titles 表示当前流程使用的 session_titles 集合。
# 返回关系：结果返回给调用层，并由调用层继续持久化、发送事件或推进运行状态。
def _scope_label(memory: Memory, workspace_names: Mapping[str, str], session_titles: Mapping[str, str]) -> str:
    if memory.scope == "global":
        return "global"
    # 变量说明：scope_id 表示scope 对象的唯一标识。
    scope_id = str(memory.scope_id or "")
    if memory.scope == "workspace":
        # 变量说明：name 表示当前对象名称。
        name = workspace_names.get(scope_id)
        return f"workspace:{scope_id}" + (f" ({name})" if name else "")
    # 变量说明：title 表示当前步骤使用的 title 值。
    title = session_titles.get(scope_id)
    return f"session:{scope_id}" + (f" ({title})" if title else "")


# 函数职责：完成 compact_text 对应的业务处理。
# 参数关系：value 表示当前字段或计算值；limit 表示当前步骤使用的 limit 值。
# 返回关系：结果返回给调用层，并由调用层继续持久化、发送事件或推进运行状态。
def _compact_text(value: str, limit: int) -> str:
    # 变量说明：text 表示当前步骤使用的 text 值。
    text = " ".join(str(value or "").split())
    return text if len(text) <= limit else text[: max(0, limit - 1)].rstrip() + "…"


# 函数职责：完成 memory_tags 对应的业务处理。
# 参数关系：memory 表示当前步骤使用的 memory 值。
# 返回关系：结果返回给调用层，并由调用层继续持久化、发送事件或推进运行状态。
def _memory_tags(memory: Memory) -> list[str]:
    return [str(tag) for tag in memory.tags] if isinstance(memory.tags, list) else []


# 函数职责：完成 render_summary 对应的业务处理。
# 参数关系：active 表示当前步骤使用的 active 值；workspace_names 表示当前流程使用的 workspace_names 集合；session_titles 表示当前流程使用的 session_titles 集合；skills 表示当前流程使用的 skills 集合。
# 返回关系：结果返回给调用层，并由调用层继续持久化、发送事件或推进运行状态。
def _render_summary(
    active: Sequence[Memory],
    workspace_names: Mapping[str, str],
    session_titles: Mapping[str, str],
    skills: Sequence[MemorySkill] = (),
) -> str:
    # 变量说明：lines 表示当前流程使用的 lines 集合。
    lines = _projection_header("PGAgent Memory Summary")
    # 变量说明：selected 表示当前步骤使用的 selected 值。
    selected = sorted(
        active,
        key=lambda item: (
            not bool(item.pinned),
            -(item.updated_at.timestamp() if isinstance(item.updated_at, datetime) else 0.0),
            item.id,
        ),
    )
    if not selected and not skills:
        lines.extend(["No active memories.", ""])
        return "\n".join(lines)
    for memory in selected:
        # 变量说明：scope 表示当前步骤使用的 scope 值。
        scope = _scope_label(memory, workspace_names, session_titles)
        # 变量说明：summary 表示当前步骤使用的 summary 值。
        summary = _compact_text(memory.description or memory.content, MEMORY_SUMMARY_ITEM_CHARS)
        # 变量说明：flags 表示当前流程使用的 flags 集合。
        flags = ", pinned" if memory.pinned else ""
        lines.extend([
            f"## {memory.name}",
            "",
            f"- ID: `{memory.id}`",
            f"- Scope: `{scope}`",
            f"- Type: `{memory.memory_type}`{flags}",
            f"- Keywords: {', '.join(f'`{tag}`' for tag in _memory_tags(memory)) or 'none'}",
            f"- Search hint: `MemorySearch {memory.name}`",
            "",
            summary,
            "",
        ])
    for skill in skills:
        lines.extend([
            f"## Skill: {skill.name}",
            "",
            f"- ID: `{skill.id}`",
            f"- Scope: `workspace:{skill.workspace_id or ''}`",
            f"- Type: `procedure`",
            f"- Keywords: {', '.join(f'`{value}`' for value in skill.keywords or []) or 'none'}",
            f"- Search hint: `MemoryRead skill_id={skill.id}`",
            "",
            _compact_text(skill.description, MEMORY_SUMMARY_ITEM_CHARS),
            "",
        ])
    return "\n".join(lines)


# 函数职责：完成 render_catalog 对应的业务处理。
# 参数关系：active 表示当前步骤使用的 active 值；workspace_names 表示当前流程使用的 workspace_names 集合；session_titles 表示当前流程使用的 session_titles 集合。
# 返回关系：结果返回给调用层，并由调用层继续持久化、发送事件或推进运行状态。
def _render_catalog(
    active: Sequence[Memory],
    workspace_names: Mapping[str, str],
    session_titles: Mapping[str, str],
) -> str:
    # 变量说明：lines 表示当前流程使用的 lines 集合。
    lines = _projection_header("PGAgent Memory Catalog")
    if not active:
        lines.extend(["No active memories.", ""])
        return "\n".join(lines)
    for memory in active:
        lines.extend([
            f"## {memory.name}",
            "",
            f"- ID: `{memory.id}`",
            f"- Scope: `{_scope_label(memory, workspace_names, session_titles)}`",
            f"- Type: `{memory.memory_type}`",
            f"- Pinned: `{'yes' if memory.pinned else 'no'}`",
            f"- Tags: {', '.join(f'`{tag}`' for tag in _memory_tags(memory)) or 'none'}",
            f"- Updated: `{memory.updated_at.isoformat() if isinstance(memory.updated_at, datetime) else ''}`",
            "",
        ])
        if memory.description:
            lines.extend([memory.description, ""])
        lines.extend(["### Content", "", memory.content, ""])
    return "\n".join(lines)


# 函数职责：完成 render_raw_memories 对应的业务处理。
# 参数关系：rows 表示当前流程使用的 rows 集合；workspace_names 表示当前流程使用的 workspace_names 集合；session_titles 表示当前流程使用的 session_titles 集合；rollouts 表示当前流程使用的 rollouts 集合。
# 返回关系：结果返回给调用层，并由调用层继续持久化、发送事件或推进运行状态。
def _render_raw_memories(
    rows: Sequence[Memory],
    workspace_names: Mapping[str, str],
    session_titles: Mapping[str, str],
    rollouts: Sequence[MemoryRollout] = (),
) -> str:
    # 变量说明：lines 表示当前流程使用的 lines 集合。
    lines = _projection_header("PGAgent Raw Memory History")
    if not rows and not rollouts:
        lines.extend(["No memory records.", ""])
        return "\n".join(lines)
    if not rows:
        lines.extend(["No consolidated memory records.", ""])
    for memory in rows:
        lines.extend([
            f"## {memory.name}",
            "",
            f"- ID: `{memory.id}`",
            f"- Status: `{memory.status}`",
            f"- Scope: `{_scope_label(memory, workspace_names, session_titles)}`",
            f"- Type: `{memory.memory_type}`",
            f"- Source session: `{memory.source_session_id or ''}`",
            f"- Source turn: `{memory.source_turn_id or ''}`",
            f"- Superseded by: `{memory.superseded_by or ''}`",
            f"- Created: `{memory.created_at.isoformat() if isinstance(memory.created_at, datetime) else ''}`",
            f"- Updated: `{memory.updated_at.isoformat() if isinstance(memory.updated_at, datetime) else ''}`",
            "",
        ])
        if memory.description:
            lines.extend([memory.description, ""])
        lines.extend([memory.content, ""])
    if rollouts:
        lines.extend(["# Phase 1 rollout outputs", ""])
        for rollout in rollouts:
            lines.extend([
                f"## {rollout.rollout_slug or rollout.id}",
                "",
                f"- Rollout ID: `{rollout.id}`",
                f"- Session: `{rollout.source_session_id}`",
                f"- CWD: `{rollout.cwd}`",
                f"- Outcome: `{rollout.outcome}`",
                f"- Status: `{rollout.status}`",
                "",
                json.dumps(list(rollout.raw_memories or []), ensure_ascii=False, indent=2),
                "",
            ])
    return "\n".join(lines)


